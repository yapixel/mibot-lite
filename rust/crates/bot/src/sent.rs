use grammers_tl_types as tl;
use std::future::Future;
use std::sync::Arc;

pub type SentCallback = Arc<dyn Fn(&tl::enums::Peer, i32) + Send + Sync>;

tokio::task_local! {
    static SENT_OBSERVER: SentCallback;
}

/// Runs `fut` with an extra per-task callback receiving newly sent `(peer, msg_id)` pairs
/// (used by `mibot-verify` to observe and clean up reply messages).
pub async fn observe_sent<F, Fut, T>(observer: SentCallback, fut: F) -> T
where
    F: FnOnce() -> Fut,
    Fut: Future<Output = T>,
{
    SENT_OBSERVER.scope(observer, fut()).await
}

pub fn current_sent_observer() -> Option<SentCallback> {
    SENT_OBSERVER.try_with(Arc::clone).ok()
}

pub async fn with_optional_sent_observer<F, Fut, T>(observer: Option<SentCallback>, fut: F) -> T
where
    F: FnOnce() -> Fut,
    Fut: Future<Output = T>,
{
    match observer {
        Some(obs) => SENT_OBSERVER.scope(obs, fut()).await,
        None => fut().await,
    }
}

/// Extracts the primary sent message ID from an `Updates` RPC response.
pub fn first_sent_message_id(updates: &tl::enums::Updates) -> Option<i32> {
    let find_in = |list: &[tl::enums::Update]| -> Option<i32> {
        for upd in list {
            match upd {
                tl::enums::Update::MessageId(u) => return Some(u.id),
                tl::enums::Update::NewMessage(u) => {
                    if let tl::enums::Message::Message(m) = &u.message {
                        return Some(m.id);
                    }
                }
                tl::enums::Update::NewChannelMessage(u) => {
                    if let tl::enums::Message::Message(m) = &u.message {
                        return Some(m.id);
                    }
                }
                _ => {}
            }
        }
        None
    };
    match updates {
        tl::enums::Updates::UpdateShortSentMessage(u) => Some(u.id),
        tl::enums::Updates::UpdateShortMessage(u) => Some(u.id),
        tl::enums::Updates::UpdateShortChatMessage(u) => Some(u.id),
        tl::enums::Updates::Updates(u) => find_in(&u.updates),
        tl::enums::Updates::Combined(u) => find_in(&u.updates),
        _ => None,
    }
}

/// Records newly sent message IDs so `UpdatesReceiver` gap-fill replays do not
/// re-dispatch messages generated by this process.
#[derive(Clone, Default)]
pub struct SentRecorder {
    mark: Option<SentCallback>,
}

impl SentRecorder {
    pub fn new(mark: SentCallback) -> Self {
        Self { mark: Some(mark) }
    }

    pub fn emit(&self, peer: &tl::enums::Peer, msg_id: i32) {
        if let Some(mark) = &self.mark {
            mark(peer, msg_id);
        }
        let _ = SENT_OBSERVER.try_with(|obs| obs(peer, msg_id));
    }

    pub fn record_updates(
        &self,
        self_id: i64,
        request_peer: Option<&tl::enums::InputPeer>,
        updates: &tl::enums::Updates,
    ) {
        match updates {
            tl::enums::Updates::UpdateShortSentMessage(u) => {
                if let Some(target) = request_peer.and_then(|p| input_peer_to_peer(self_id, p)) {
                    self.emit(&target, u.id);
                }
            }
            tl::enums::Updates::Updates(u) => self.mark_list(&u.updates),
            tl::enums::Updates::Combined(u) => self.mark_list(&u.updates),
            tl::enums::Updates::UpdateShort(u) => self.mark_list(std::slice::from_ref(&u.update)),
            _ => {}
        }
    }

    fn mark_list(&self, list: &[tl::enums::Update]) {
        for item in list {
            let msg = match item {
                tl::enums::Update::NewMessage(u) => &u.message,
                tl::enums::Update::NewChannelMessage(u) => &u.message,
                _ => continue,
            };
            if let tl::enums::Message::Message(plain) = msg {
                self.emit(&plain.peer_id, plain.id);
            }
        }
    }
}

pub fn input_peer_to_peer(self_id: i64, input: &tl::enums::InputPeer) -> Option<tl::enums::Peer> {
    match input {
        tl::enums::InputPeer::PeerSelf => {
            (self_id != 0).then(|| tl::types::PeerUser { user_id: self_id }.into())
        }
        tl::enums::InputPeer::User(u) => Some(tl::types::PeerUser { user_id: u.user_id }.into()),
        tl::enums::InputPeer::Chat(c) => Some(tl::types::PeerChat { chat_id: c.chat_id }.into()),
        tl::enums::InputPeer::Channel(ch) => {
            Some(tl::types::PeerChannel { channel_id: ch.channel_id }.into())
        }
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::peers::peer_id;
    use std::sync::Mutex;

    #[test]
    fn records_short_sent_and_updates_but_skips_edits() {
        let marks: Arc<Mutex<Vec<(String, i32)>>> = Arc::new(Mutex::new(Vec::new()));
        let marks_ref = marks.clone();
        let recorder = SentRecorder::new(Arc::new(move |peer, id| {
            marks_ref.lock().unwrap().push((peer_id(peer), id));
        }));

        // 1. Saved Messages UpdateShortSentMessage
        let short = tl::enums::Updates::UpdateShortSentMessage(tl::types::UpdateShortSentMessage {
            out: true,
            id: 10,
            pts: 1,
            pts_count: 1,
            date: 0,
            media: None,
            entities: None,
            ttl_period: None,
        });
        recorder.record_updates(1, Some(&tl::enums::InputPeer::PeerSelf), &short);
        assert_eq!(*marks.lock().unwrap(), vec![("1".to_owned(), 10)]);
        marks.lock().unwrap().clear();

        // 2. Updates batch with NewChannelMessage + EditChannelMessage
        let new_msg = tl::enums::Message::Message(tl::types::Message {
            out: true,
            mentioned: false,
            media_unread: false,
            silent: false,
            post: false,
            from_scheduled: false,
            legacy: false,
            edit_hide: false,
            pinned: false,
            noforwards: false,
            invert_media: false,
            offline: false,
            video_processing_pending: false,
            paid_suggested_post_stars: false,
            paid_suggested_post_ton: false,
            id: 30,
            from_id: None,
            from_boosts_applied: None,
            from_rank: None,
            peer_id: tl::types::PeerChannel { channel_id: 9 }.into(),
            saved_peer_id: None,
            fwd_from: None,
            via_bot_id: None,
            via_business_bot_id: None,
            guestchat_via_from: None,
            reply_to: None,
            date: 0,
            message: String::new(),
            media: None,
            reply_markup: None,
            entities: None,
            views: None,
            forwards: None,
            replies: None,
            edit_date: None,
            post_author: None,
            grouped_id: None,
            reactions: None,
            restriction_reason: None,
            ttl_period: None,
            quick_reply_shortcut_id: None,
            effect: None,
            factcheck: None,
            report_delivery_until_date: None,
            paid_message_stars: None,
            suggested_post: None,
            schedule_repeat_period: None,
            summary_from_language: None,
            rich_message: None,
        });
        let edit_msg = tl::enums::Message::Message(match new_msg.clone() {
            tl::enums::Message::Message(mut m) => {
                m.id = 31;
                m
            }
            _ => unreachable!(),
        });
        let batch = tl::enums::Updates::Updates(tl::types::Updates {
            updates: vec![
                tl::types::UpdateMessageId { id: 30, random_id: 5 }.into(),
                tl::types::UpdateNewChannelMessage {
                    message: new_msg,
                    pts: 1,
                    pts_count: 1,
                }
                .into(),
                tl::types::UpdateEditChannelMessage {
                    message: edit_msg,
                    pts: 2,
                    pts_count: 1,
                }
                .into(),
            ],
            users: vec![],
            chats: vec![],
            date: 0,
            seq: 0,
        });
        recorder.record_updates(1, None, &batch);
        assert_eq!(*marks.lock().unwrap(), vec![("-1009".to_owned(), 30)]);
    }
}
